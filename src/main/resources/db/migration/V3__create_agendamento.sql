CREATE TABLE agendamento (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id          BIGINT      NOT NULL REFERENCES cliente (id),
    servico_id          BIGINT      NOT NULL REFERENCES servico (id),
    inicio              TIMESTAMPTZ NOT NULL,
    fim                 TIMESTAMPTZ NOT NULL,
    status              VARCHAR(20) NOT NULL CHECK (status IN ('AGENDADO', 'CONFIRMADO', 'CANCELADO')),
    lembrete_enviado_em TIMESTAMPTZ,
    criado_em           TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (fim > inicio),
    -- Garante no banco que dois agendamentos ativos nunca se sobrepõem,
    -- mesmo com requisições concorrentes. Cancelados liberam o horário.
    CONSTRAINT agendamento_sem_sobreposicao
        EXCLUDE USING gist (tstzrange(inicio, fim, '[)') WITH &&)
        WHERE (status <> 'CANCELADO')
);

CREATE INDEX idx_agendamento_status_inicio ON agendamento (status, inicio);
CREATE INDEX idx_agendamento_cliente ON agendamento (cliente_id);
